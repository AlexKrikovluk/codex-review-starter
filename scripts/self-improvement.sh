#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPORT_DIR="$HOME/.hermes/cron/output/self-improvement"
DATE=$(date +%Y-%m-%d)
REPORT="$REPORT_DIR/self-improvement-$DATE.md"
mkdir -p "$REPORT_DIR"

PROJECTS=(
  "$HOME/projects/python-scripts"
  "$HOME/projects/codex-review-starter"
)

run_check() {
  local label="$1"
  local cmd="$2"
  echo "### $label"
  set +e
  eval "$cmd" 2>&1 | tail -n 20
  local rc=$?
  set -e
  if [ "$rc" -eq 0 ]; then
    echo "_OK_"
  else
    echo "_FAILED_"
  fi
  echo ""
}

{
  echo "# 🛠️ Self-Improvement Report"
  echo ""
  echo "**Date:** $DATE"
  echo "**Mode:** Nightly automated checks"
  echo ""
  echo "---"
  echo ""

  for PROJECT in "${PROJECTS[@]}"; do
    NAME=$(basename "$PROJECT")
    echo "## $NAME"
    echo ""

    if [ ! -d "$PROJECT" ]; then
      echo "_Project missing._"
      echo ""
      continue
    fi

    pushd "$PROJECT" >/dev/null

    VENV="$PROJECT/.venv"
    if [ -d "$VENV/bin" ]; then
      PATH="$VENV/bin:$PATH"
    fi

    if [ -d "$VENV/bin" ] && ! command -v pytest >/dev/null 2>&1; then
      "$VENV/bin/python" -m pip install -q pytest pytest-cov || true
    fi
    if [ -d "$VENV/bin" ] && command -v pytest >/dev/null 2>&1 && ! "$VENV/bin/python" -c "import pytest_cov" 2>/dev/null; then
      "$VENV/bin/python" -m pip install -q pytest-cov || true
    fi
    if [ -d "$VENV/bin" ] && ! command -v mypy >/dev/null 2>&1; then
      "$VENV/bin/python" -m pip install -q mypy || true
    fi
    if [ -d "$VENV/bin" ] && ! command -v ruff >/dev/null 2>&1; then
      "$VENV/bin/python" -m pip install -q ruff || true
    fi

    # Auto-fix what we can
    if [ -d "$VENV/bin" ] && command -v ruff >/dev/null 2>&1; then
      ruff check . --fix || true
    fi
    find . -type d -name __pycache__ -exec rm -rf {} + 2>/dev/null || true

    run_check "pytest" "pytest -q"
    run_check "mypy strict" "mypy ."
    run_check "ruff" "ruff check ."

    # Auto-commit trivial fixes if git repo and changes exist
    if [ -d .git ]; then
      if git diff --quiet 2>/dev/null; then
        :
      else
        git add -A 2>/dev/null || true
        git commit -m "chore: nightly auto-fixes ruff/pycache $(date +%Y-%m-%d)" 2>/dev/null || true
      fi
    fi

    popd >/dev/null
  done

  echo "---"
  echo ""
  echo "*Auto-generated by self-improvement.sh*"
} > "$REPORT"

echo "$REPORT"
