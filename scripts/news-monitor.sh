#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPORT_DIR="$HOME/.hermes/cron/output/news-digest"
DATE=$(date +%Y-%m-%d)
REPORT="$REPORT_DIR/digest-$DATE.md"
mkdir -p "$REPORT_DIR"

cat > "$REPORT" <<'EOF'
# 📰 Daily Tech Digest

**Date:** DATE_PLACEHOLDER
**Sources:** GitHub Trending, Product Hunt, HN, Reddit, OpenAI/Codex blogs, X/Twitter

---

## 1. 🎯 Your Product & Brand
*Mentions of `codex-review-starter`, `AlexKrikovluk`, Gumroad listing*

_None today. Check back tomorrow._

---

## 2. 🛠️ Competitors & Alternatives
*AI code review tools, Codex CLI wrappers, automation templates*

_Scanning for competitors..._

---

## 3. 🌐 Ecosystem
*OpenAI/Codex/Anthropic releases, Python tools, devtools trends*

_Scanning ecosystem..._

---

## 4. 💡 Indie Hackers
*Product Hunt launches, HN discussions, Reddit digital products*

_Scanning indie hacker scene..._

---

## 5. 🎬 Content Trends
*YouTube Shorts gaming/humor trends, viral hooks*

_Scanning content trends..._

---

## 🔥 Top Stories

1. _No top stories yet._

---

*Auto-generated by news-monitor.sh*
EOF

sed -i "s/DATE_PLACEHOLDER/$DATE/" "$REPORT"
echo "$REPORT"
